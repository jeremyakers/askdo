package main

import (
	"encoding/hex"
	"errors"
	"fmt"
	"path/filepath"
	"regexp"
	"runtime"
	"strings"

	"github.com/jeremyakers/askdo/internal/upgrade"
)

// The bootstrap shares the receipt parent on an executable filesystem, not
// /run or /tmp. Receipt scanning recognizes its private operation directories.
const defaultUpgradeBootstrapRoot = defaultUpgradeReceiptRoot

// upgradeBootstrapScript verifies a root-owned copy before executing the new
// helper through a pinned file descriptor. The old installed helper is not
// involved, and path replacement cannot change the verified inode before exec.
// upgradeRepository is the release source askdo upgrade downloads from.
const upgradeRepository = "jeremyakers/askdo"

var (
	upgradeReleaseTag   = regexp.MustCompile(`^v[0-9A-Za-z.+-]{1,64}$`)
	upgradeSourceCommit = regexp.MustCompile(`^[0-9a-f]{40}$`)
)

func upgradeBootstrapScript(plan upgrade.Plan, capturedPlan []byte, bootstrapRoot string) ([]byte, error) {
	if !filepath.IsAbs(bootstrapRoot) || filepath.Clean(bootstrapRoot) != bootstrapRoot || strings.ContainsAny(bootstrapRoot, "'\n\r") {
		return nil, errors.New("upgrade bootstrap root must be a clean absolute path")
	}
	if len(capturedPlan) == 0 || strings.ContainsAny(string(capturedPlan), "'\n\r") {
		return nil, errors.New("upgrade plan cannot be embedded safely")
	}
	if !upgradeRuntimeOperation.MatchString(plan.Operation) || plan.CLIAsset != "askdo-linux-"+runtime.GOARCH || len(plan.CLIDigest) != 64 {
		return nil, errors.New("upgrade bootstrap plan identity is invalid")
	}
	if _, err := hex.DecodeString(plan.CLIDigest); err != nil {
		return nil, errors.New("upgrade bootstrap CLI digest is invalid")
	}
	if !upgradeReleaseTag.MatchString(plan.Release) || !upgradeSourceCommit.MatchString(plan.SourceCommit) {
		return nil, errors.New("upgrade bootstrap release identity is invalid")
	}
	bootstrap := filepath.Join(bootstrapRoot, "bootstrap-"+plan.Operation)
	candidate := filepath.Join(bootstrap, plan.CLIAsset)
	// The provenance header gives the AI reviewer the facts it needs to check
	// this request independently instead of trusting the wrapper: the official
	// published checksum for the exact asset (compare with the digest this
	// script enforces) and the documented helper behavior at the exact commit.
	header := fmt.Sprintf(`# askdo self-upgrade bootstrap, generated by "askdo upgrade".
# Release %[1]s, source commit %[2]s.
# It installs a root-private copy of %[4]s and runs it only if its SHA-256 is
#   %[5]s
# Independent check: the official published checksum for this asset is
#   https://github.com/%[3]s/releases/download/%[1]s/%[4]s.sha256
# and every release asset digest is listed in
#   https://github.com/%[3]s/releases/download/%[1]s/install-manifest.v1
# The verified binary's upgrade-helper only schedules the upgrade. After this
# job ends it re-verifies all staged assets, drains askdo admission, backs up the
# broker and gateway databases and binaries, installs the release and verifies
# the restarted services. If activation fails after any service stop, it
# automatically restores the backed-up binaries, config and databases, restarts
# the previous release and verifies it; see
#   https://raw.githubusercontent.com/%[3]s/%[2]s/docs/upgrade.md
`, plan.Release, plan.SourceCommit, upgradeRepository, plan.CLIAsset, plan.CLIDigest)
	script := header + fmt.Sprintf(`set -eu
operation=$1
source=$2
root='%s'
bootstrap='%s'
candidate='%s'
if [ ! -e "$root" ]; then
  /usr/bin/install -d -m 0700 "$root"
fi
owner=$(/usr/bin/stat -c '%%u' "$root")
mode=$(/usr/bin/stat -c '%%a' "$root")
kind=$(/usr/bin/stat -c '%%F' "$root")
if [ "$owner" != "$(/usr/bin/id -u)" ] || [ "$kind" != directory ] || [ -L "$root" ]; then
  printf 'untrusted bootstrap root: %%s\n' "$root" >&2
  exit 1
fi
case "$mode" in
  700|750|755) ;;
  *) printf 'untrusted bootstrap root mode: %%s\n' "$mode" >&2; exit 1 ;;
esac
/bin/mkdir -m 0700 "$bootstrap"
trap '/bin/rm -rf -- "$bootstrap"' EXIT
/usr/bin/install -m 0700 "$source/%s" "$candidate"
exec 3<"$candidate"
printf '%%s  %%s\n' '%s' /proc/self/fd/3 | /usr/bin/sha256sum --quiet -c -
status=0
printf '%%s' '%s' | /proc/self/fd/3 upgrade-helper --operation "$operation" --source "$source" || status=$?
exit "$status"
`, bootstrapRoot, bootstrap, candidate, plan.CLIAsset, plan.CLIDigest, capturedPlan)
	return []byte(script), nil
}
